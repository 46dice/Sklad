// Основная структура ответа
interface ApiResponse {
	items: Item[]
}

interface Item {
	ИП: IPData
}

// Основные данные ИП
interface IPData {
	ФИОПолн: string
	ИННФЛ: string
	ОГРНИП: string
	ДатаОГРН: string // Дата в формате YYYY-MM-DD
	ДатаРег: string // Дата в формате YYYY-MM-DD
	ВидИП: string
	Пол: 'Мужской' | 'Женский' // Предполагаем возможные значения
	ВидГражд: string
	Статус: 'Действующее' | 'Недействующее' | 'Ликвидировано' // Предполагаем возможные значения
	НО: TaxAuthority
	ПФ: PensionFund
	КодыСтат: StatisticsCodes
	Адрес: Address
	'E-mail'?: string // Опционально, так как может быть не всегда
	Контакты: Contacts
	ОснВидДеят: Activity
	ДопВидДеят: Activity[] // Массив дополнительных видов деятельности
	СПВЗ: RegistrationEvent[]
	ОткрСведения?: OpenInfo // Опционально, может отсутствовать
	История: History
}

// Налоговые органы
interface TaxAuthority {
	Рег: string
	РегДата: string // Дата в формате YYYY-MM-DD
	Учет: string
	УчетДата: string // Дата в формате YYYY-MM-DD
}

// Пенсионный фонд
interface PensionFund {
	РегНомПФ: string
	ДатаРегПФ: string // Дата в формате YYYY-MM-DD
	КодПФ: string
}

// Коды статистики
interface StatisticsCodes {
	ОКПО: string
	ОКТМО: string
	ОКФС: string
	ОКОГУ: string
}

// Адрес
interface Address {
	КодРегион: string
	Индекс: string | null
	АдресПолн: string
	Дата: string // Дата в формате YYYY-MM-DD
}

// Контакты
interface Contacts {
	'e-mail'?: string[] // Опционально, массив email'ов
}

// Вид деятельности
interface Activity {
	Код: string
	Текст: string
	Дата: string // Дата в формате YYYY-MM-DD
}

// Событие регистрации
interface RegistrationEvent {
	Дата: string // Дата в формате YYYY-MM-DD
	Текст: string
}

// Открытые сведения
interface OpenInfo {
	СведСНР: string // Система налогообложения
	Дата: string // Дата в формате YYYY-MM-DD
}

// История изменений
interface History {
	'E-mail'?: EmailHistory
	// Здесь могут быть и другие поля истории, если они появятся
	[key: string]: EmailHistory | undefined // Индексная сигнатура для гибкости
}

// История email'ов
interface EmailHistory {
	[dateRange: string]: string // Ключ - диапазон дат, значение - email
}

